function warrantyNote(meta, cls) {
  const parts = [];
  parts.push(meta.src
    ? 'Source warranty period: 6 months (Madhouse Warranty Repair Matrix).'
    : 'Warranty period not stated in the source references; apply the contract and Certificate of Completion terms.');
  if (meta.sup) parts.push('Product defects may fall under the supplier or manufacturer warranty; coordinate supplier claim.');
  if (meta.excl) parts.push(meta.excl);
  if (cls === 'Critical') parts.push('Make-safe works proceed immediately regardless of coverage; liability is determined after investigation.');
  parts.push('Coverage subject to validation: excludes owner misuse, alterations by others, normal wear and tear, and damage from external events.');
  return parts.join(' ');
}

export function buildLibrary() {
  const counters = {};
  const nameToId = {};
  const items = ROWS.map((r) => {
    const [sub, name, cls, trade, min, max, duration, priority, description, causes, method, meta] = r;
    const prof = SUBCATEGORIES[sub];
    const c = prof.cat;
    counters[c] = (counters[c] || 0) + 1;
    const id = `MS-${c}-${String(counters[c]).padStart(3, '0')}`;
    nameToId[name] = id;
    const mid = (min + max) / 2;
    const [l, m, e] = SPLITS[prof.qa] || SPLITS.carpentry;
    return {
      id,
      category: CATEGORIES[c],
      catCode: c,
      subcategory: prof.name,
      subCode: sub,
      item: name,
      description,
      symptoms: prof.symptoms,
      causes,
      inspection: prof.inspect,
      method,
      minorCriteria: prof.minor,
      majorCriteria: prof.major,
      criticalCriteria: prof.critical,
      trade,
      laborCost: round50(mid * l),
      materialCost: round50(mid * m),
      equipmentCost: round50(mid * e),
      costMin: min,
      costMax: max,
      duration,
      priority,
      classification: cls,
      qaTemplate: prof.qa,
      qaVerification: QA_TEMPLATES[prof.qa].items.filter((x) => x[1]).map((x) => x[0]).join('; '),
      warrantyNotes: warrantyNote(meta, cls),
      sourceRef: meta.src ? `WRM-${String(meta.src).padStart(2, '0')}` : 'MS-NEW',
      crcRefs: meta.crc || [],
      sourcePriority: meta.sp || '',
      commonGroup: meta.common || '',
      scaleTo: meta.scale || '',
    };
  });
  items.forEach((it) => { if (it.scaleTo) it.scaleToId = nameToId[it.scaleTo] || ''; });
  return items;
}

// Consolidation register: every change between source records and the Madhouse Standard library.
export function buildConsolidationLog(items) {
  const log = [];
  for (const it of items) {
    if (it.sourceRef === 'MS-NEW') continue;
    const n = parseInt(it.sourceRef.slice(4), 10);
    log.push({ type: 'Preserved', ref: it.sourceRef, id: it.id,
      note: `"${it.item}" kept with source classification (${it.classification}), trade, duration and cost range.` });
    if (WRM_SOURCE_COST[n]) {
      const [smin, smax] = WRM_SOURCE_COST[n];
      log.push({ type: 'Cost range widened', ref: it.sourceRef, id: it.id,
        note: `Source matrix ₱${smin.toLocaleString()}–₱${smax.toLocaleString()}; merged CRC entry starts lower, so the range is now ₱${it.costMin.toLocaleString()}–₱${it.costMax.toLocaleString()}.` });
    }
    for (const c of it.crcRefs) {
      const [cn, cd, cmin, cmax] = CRC_ENTRIES[c];
      log.push({ type: 'Duplicate merged', ref: c, id: it.id,
        note: `CRC "${cn}" (${cd}, ₱${cmin.toLocaleString()}–₱${cmax.toLocaleString()}) merged into ${it.sourceRef} "${it.item}".` });
    }
    const mapped = SRC_PRIORITY_MAP[it.sourcePriority];
    if (it.sourcePriority && it.priority !== mapped) {
      log.push({ type: 'Priority mapped', ref: it.sourceRef, id: it.id,
        note: `Source priority "${it.sourcePriority}" mapped to ${it.priority} ${it.sourcePriority === 'Low' ? (it.priority === 'P4' ? '(appearance-only defect)' : '(functional defect, not cosmetic)') : '(capacity upgrade rather than an active defect)'}.` });
    }
    if (it.classification === 'Major' && it.costMin < 15000) {
      log.push({ type: 'Observation', ref: it.sourceRef, id: it.id,
        note: `Classified Major in the source although the minimum cost (₱${it.costMin.toLocaleString()}) is below the ₱15,000 Major guide. Retained: scope, not cost alone, sets the classification.` });
    }
  }
  return log;
}
